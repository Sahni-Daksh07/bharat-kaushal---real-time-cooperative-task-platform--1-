// Calculation helper for revenue split
export function calculateRevenueSplit(
  amount: number,
  policy: CooperativePolicy = INITIAL_POLICY
): {
  grossAmount: number;
  workerShare: number;
  societyShare: number;
  welfareShare: number;
  model: string;
} {
  if (policy.activeModel === 'MODEL_A') {
    // 94.5% Worker, 3.5% Society, 2.0% Welfare
    // For ₹499: Worker = 471.555 (471.55), Society = 17.465 (17.47), Welfare = 9.980 (9.98)
    const workerShare = Math.round((amount * policy.modelA.workerSharePercent / 100) * 100) / 100;
    const societyShare = Math.round((amount * policy.modelA.societySharePercent / 100) * 100) / 100;
    const welfareShare = Math.round((amount * policy.modelA.welfareFundPercent / 100) * 100) / 100;
    return {
      grossAmount: amount,
      workerShare,
      societyShare,
      welfareShare,
      model: 'Society Cooperative Model (94.5% / 3.5% / 2.0%)',
    };
  } else {
    // Model B: 95.0% Worker, 2.5% Maintenance, 2.5% Welfare
    const workerShare = Math.round((amount * policy.modelB.workerSharePercent / 100) * 100) / 100;
    const societyShare = Math.round((amount * policy.modelB.maintenancePercent / 100) * 100) / 100;
    const welfareShare = Math.round((amount * policy.modelB.welfareFundPercent / 100) * 100) / 100;
    return {
      grossAmount: amount,
      workerShare,
      societyShare,
      welfareShare,
      model: 'Platform Commission Model (95.0% / 2.5% / 2.5%)',
    };
  }
}

